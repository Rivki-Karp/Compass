"""The README's results block, generated from committed files only (Day 5 Stage 7).

    uv run --project backend python tasks.py readme   # rewrites the block between the markers

The eval summary and table are copied from evals/report.md as they are; the test counts come
from tests/counts.json; cost per conversation and total spend are computed exactly as judges mode
computes them (compass/api/stats.py). tests/test_readme_numbers.py fails when the committed
README's block is stale, so no number in it is ever typed by hand.
"""

from pathlib import Path

from compass.api.stats import REPORT, SPEND, TEST_COUNTS, judges_stats
from compass.config import REPO_ROOT

README = REPO_ROOT / "README.md"
START = (
    "<!-- results:start · generated by `uv run --project backend python tasks.py readme`; "
    "do not edit -->"
)
END = "<!-- results:end -->"


class ReadmeNumbersError(ValueError):
    """A source file is missing or the README has no results markers."""


def report_summary(text: str) -> str:
    """The report's summary bullets and its per-scenario table, verbatim."""
    lines = text.splitlines()
    try:
        start = next(i for i, line in enumerate(lines) if line.startswith("- Run:"))
        end = next(i for i, line in enumerate(lines) if line.startswith("Per-scenario figures"))
    except StopIteration:
        raise ReadmeNumbersError("evals/report.md: no summary or table found") from None
    return "\n".join(lines[start : end + 1])


def numbers_block(report: Path = REPORT, spend: Path = SPEND, counts: Path = TEST_COUNTS) -> str:
    stats = judges_stats(report=report, spend=spend, test_counts=counts)
    tests, ledger, per = stats["tests"], stats["spend"], stats["cost_per_conversation"]
    if tests is None or ledger is None or per is None:
        raise ReadmeNumbersError("evals/report.md, evals/spend.jsonl or tests/counts.json")
    e2e = f" · Playwright **{tests['e2e']}**" if tests.get("e2e") is not None else ""
    return "\n".join(
        [
            START,
            "",
            "**Agent evals** ([backend/evals/report.md](backend/evals/report.md), the last full "
            "run against the real model):",
            "",
            report_summary(report.read_text(encoding="utf-8")),
            "",
            "**Tests** ([backend/tests/counts.json](backend/tests/counts.json), "
            f"{tests['as_of']}): pytest **{tests['pytest']}** · vitest **{tests['vitest']}**{e2e}. "
            "CI runs all of them on every push.",
            "",
            f"**Cost per conversation:** **${per['usd']}**, the last report's run cost over its "
            f"{per['runs']} scenario runs.",
            "",
            f"**Total spend on evals:** **${ledger['total_usd']}** of the "
            f"${ledger['cap_usd']} cap, over every eval run so far: {ledger['calls']} scenario "
            "runs ([backend/evals/spend.jsonl](backend/evals/spend.jsonl)).",
            "",
            END,
        ]
    )


def render(readme: str, block: str) -> str:
    """The README with its results block replaced by `block`."""
    head, found, rest = readme.partition(START)
    _, found_end, tail = rest.partition(END)
    if not found or not found_end:
        raise ReadmeNumbersError("README.md has no results markers")
    return head + block + tail


def main() -> None:
    text = README.read_text(encoding="utf-8")
    updated = render(text, numbers_block())
    README.write_text(updated, encoding="utf-8", newline="\n")
    print("README.md: results block " + ("updated" if updated != text else "already current"))


if __name__ == "__main__":
    main()
